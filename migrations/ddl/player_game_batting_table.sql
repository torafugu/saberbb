    game_id INTEGER,
    count_seq INTEGER,
    pitcher_id INTEGER NOT NULL,
    batter_id INTEGER NOT NULL,
    timing_error REAL NOT NULL,
    bat_speed REAL NOT NULL,
    angular_velocity REAL NOT NULL,
    approach_variation_deg REAL NOT NULL,
    pull_bias_deg REAL NOT NULL,
    timing_angle_error REAL NOT NULL,
    final_hla_deg REAL NOT NULL,
    adapted_horizontal_offset_m REAL,
    adapted_vertical_offset_m REAL,
    adapted_timing_offset_sec REAL,
    timing_impact_x_m REAL,
    swing_error_x_m REAL,
    swing_error_z_m REAL,
    contact_offset_x_m REAL,
    contact_offset_z_m REAL,
    thickness_offset_m REAL,
    length_offset_m REAL NOT NULL,
    original_contact_type TEXT NOT NULL,
    adjusted_contact_type TEXT NOT NULL,
    launch_speed REAL NOT NULL,
    launch_angle REAL NOT NULL,
    polar_distance REAL NOT NULL,
    polar_angle REAL NOT NULL,
    total_time REAL NOT NULL,
    first_bounce_distance REAL,
    first_bounce_angle REAL,
    first_bounce_time REAL,
    fence_impact_distance REAL,
    fence_impact_angle REAL,
    fence_impact_time REAL,
    outbound_result TEXT NOT NULL,
    fielder_position TEXT,
    result TEXT NOT NULL,
    decision_count_status TEXT,
    decision_location_x REAL,
    decision_location_y REAL,
    decision_count_factor REAL,
    decision_approach_factor REAL,
    decision_protection_factor REAL,
    decision_zone_factor REAL,
    decision_pitch_factor REAL,
    decision_anticipation_factor REAL,
    decision_aptitude_factor REAL,
    decision_score REAL,
    decision_probability REAL,
    decision_swung INTEGER,
    actual_bat_angle_deg REAL,
    timing_position_scale REAL CHECK (timing_position_scale > 0),
    PRIMARY KEY (game_id, count_seq)
